def get_categories():
    categories = set()
    for item in COMMODITIES_DB.values():
        categories.add(item["category"])
    return sorted(list(categories))

def get_commodities_by_category(category_name):
    return [name for name, data in COMMODITIES_DB.items() if data["category"] == category_name]
